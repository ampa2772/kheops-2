/**
 * Normalise un nom de ville pour la recherche dans le mapping :
 * minuscule, sans accents, espaces remplaces par des tirets, apostrophes unifiees.
 */
function normalizeCity(city) {
  return (city || "")
    .normalize("NFD").replace(/[̀-ͯ]/g, "")
    .toLowerCase().trim()
    .replace(/[’‘ʼ]/g, "'")
    .replace(/\s+/g, "-");
}

/**
 * Construit "Avocat au Barreau de/du/des/de la/de l'..." a partir du nom du barreau.
 * Gere automatiquement les prepositions francaises.
 */
function buildBarreauComplet(barreauNom) {
  if (!barreauNom) return "Avocat au Barreau";
  var lower = barreauNom.toLowerCase();
  // "du" et "des" sont deja des contractions de "de le" / "de les"
  // => pas de "de" supplementaire
  if (lower.startsWith("du ") || lower.startsWith("des ")) {
    return "Avocat au Barreau " + barreauNom;
  }
  // Elision devant voyelle ou h muet : "de Agen" -> "d'Agen", "de Angers" -> "d'Angers"
  var firstChar = lower.charAt(0);
  if ("aeiouyéèêëàâäùûüôöîï".indexOf(firstChar) >= 0) {
    return "Avocat au Barreau d'" + barreauNom;
  }
  // Tous les autres cas : "de Paris", "de l'Eure", "de la Martinique", etc.
  return "Avocat au Barreau de " + barreauNom;
}

/**
 * Retourne le nom du barreau pour une ville donnee.
 * Si explicitBarreau est fourni (champ profil), il est prioritaire.
 * Sinon, cherche par ville dans le mapping (2138 villes).
 * Ex : getBarreauName("Bernay") => "l'Eure"
 *      getBarreauName("Paris") => "Paris"
 *      getBarreauName("Nanterre") => "des Hauts-de-Seine"
 */
function getBarreauName(city, explicitBarreau) {
  if (explicitBarreau) return explicitBarreau;
  var key = normalizeCity(city);
  return barreaux[key] || city || "";
}

/**
 * Retourne la liste triee de tous les noms de barreaux (valeurs uniques).
 * Utilisee pour alimenter le dropdown dans le profil.
 */
function getAllBarreauxNames() {
  var names = [...new Set(Object.values(barreaux))];
  return names.sort(function(a, b) { return a.localeCompare(b, "fr"); });
}

